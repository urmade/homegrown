import { mkdirSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join, relative } from "node:path";
import { loadManifests, repoRoot } from "./manifest";

const HEADER = "// Generated by `pnpm gen` from apps/*/module.json. Do not edit.\n";
const camel = (s: string) => s.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());

function write(file: string, body: string) {
  mkdirSync(join(file, ".."), { recursive: true });
  writeFileSync(file, HEADER + body);
}

/**
 * Emits the module registry (server functions and pages) and one typed client per module.
 * A client only contains the capabilities the module declares in `calls`, so undeclared calls fail tsc.
 */
export function generateRegistry(root = repoRoot()) {
  const mods = loadManifests(root);
  const out = join(root, ".homegrown");
  const rel = (to: string) => relative(out, to).replaceAll("\\", "/");

  const locales = (dir: string) =>
    existsSync(join(dir, "messages")) ? readdirSync(join(dir, "messages")).filter((f) => /^[a-z]{2}(-[A-Z]{2})?\.json$/.test(f)).sort().map((f) => f.slice(0, -5)) : [];
  const id = (m: { manifest: { name: string } }) => camel(m.manifest.name);

  write(
    join(out, "registry.server.ts"),
    mods
      .map((m) =>
        [
          `import ${id(m)}Manifest from "${rel(join(m.dir, "module.json"))}";`,
          `import * as ${id(m)}Fns from "${rel(join(m.dir, "src/functions"))}";`,
          ...locales(m.dir).map((l) => `import ${id(m)}_${l.replace("-", "_")} from "${rel(join(m.dir, "messages", `${l}.json`))}";`),
        ].join("\n"),
      )
      .join("\n") +
      `\nimport { ModuleManifest } from "../core/src/manifest";\nimport type { RegisteredModule } from "../core/src/runtime";\n\nexport const modules: RegisteredModule[] = [\n${mods
        .map(
          (m) =>
            `  { manifest: ModuleManifest.parse(${id(m)}Manifest), functions: ${id(m)}Fns as Record<string, unknown>, messages: { ${locales(m.dir)
              .map((l) => `"${l}": ${id(m)}_${l.replace("-", "_")}`)
              .join(", ")} } },`,
        )
        .join("\n")}\n];\n`,
  );

  write(
    join(out, "registry.pages.ts"),
    mods
      .filter((m) => existsSync(join(m.dir, "src/page.tsx")))
      .map((m) => `import ${camel(m.manifest.name)}Page from "${rel(join(m.dir, "src/page"))}";`)
      .join("\n") +
      `\n\nexport const pages: Record<string, (props: { path: string[] }) => unknown> = {\n${mods
        .filter((m) => existsSync(join(m.dir, "src/page.tsx")))
        .map((m) => `  "${m.manifest.name}": ${camel(m.manifest.name)}Page,`)
        .join("\n")}\n};\n`,
  );

  for (const m of mods) {
    const byModule = new Map<string, Set<string>>();
    for (const f of m.manifest.functions)
      for (const c of f.calls) {
        const [mod, cap] = c.split(".") as [string, string];
        (byModule.get(mod) ?? byModule.set(mod, new Set()).get(mod)!).add(cap);
      }
    const imports = [...byModule.keys()].map((mod) => `import type * as ${camel(mod)} from "../../${mod}/src/functions";`);
    const fields = [...byModule].map(([mod, caps]) => `  "${mod}": ClientOf<typeof ${camel(mod)}, ${[...caps].map((c) => `"${c}"`).join(" | ")}>;`);
    write(
      join(m.dir, ".generated/client.ts"),
      `import type { ClientOf } from "@homegrown/core";\n${imports.join("\n")}\n\nexport type Calls = {\n${fields.join("\n")}\n};\n`,
    );
  }
  return mods;
}
