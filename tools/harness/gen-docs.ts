import { writeFileSync } from "node:fs";
import { buildDataFlow, type DataFlow } from "../../core/src/dataflow";
import { loadManifests } from "../../core/src/manifest";
import { done, fail, read } from "./lib";

/**
 * The one generator. data-flow.json comes from core (it needs a migrated DB: `pnpm gen:data-flow`);
 * CAPABILITIES.md and FEATURES.md are rendered from the same declarations and committed.
 * `--check` fails when the committed files are stale.
 */
const manifests = loadManifests().map((m) => m.manifest);
const flow: DataFlow = buildDataFlow(manifests, []);
const HEADER = "<!-- Generated by `pnpm gen:docs` from module.json via data-flow. Do not edit. -->\n\n";

const consumers = (cap: string) => flow.calls.filter((c) => c.to === cap).map((c) => c.from);

const capabilities =
  HEADER +
  "# Capabilities\n\nExported cross-module functions. Reuse one before adding a new module, table or capability.\n\n" +
  (flow.modules.flatMap((m) => Object.entries(m.exports).map(([name, description]) => ({ id: `${m.name}.${name}`, description }))).map(
    (c) => `- \`${c.id}\`: ${c.description}${consumers(c.id).length ? ` Used by: ${consumers(c.id).map((x) => `\`${x}\``).join(", ")}.` : " Unused."}`,
  ).join("\n") || "_None yet._") +
  "\n";

const features =
  HEADER +
  "# Features\n\n" +
  (manifests
    .map((m) =>
      [
        `## ${m.title} (\`${m.name}\`)`,
        "",
        m.description,
        "",
        `- Tables: ${m.tables.map((t) => `\`${t}\``).join(", ") || "none"}`,
        `- Functions: ${m.functions.map((f) => `\`${f.name}\``).join(", ")}`,
        `- Calls: ${[...new Set(m.functions.flatMap((f) => f.calls))].map((c) => `\`${c}\``).join(", ") || "none"}`,
        `- Offline: ${m.offline ? `${m.offline.strategy}, writes ${m.offline.offlineWrites}` : "default (network-only with offline notice)"}`,
      ].join("\n"),
    )
    .join("\n\n") || "_No modules yet._") +
  "\n";

const outputs = { "CAPABILITIES.md": capabilities, "FEATURES.md": features };
for (const [file, body] of Object.entries(outputs)) {
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = read(file);
    } catch {}
    if (current !== body) fail(`${file} is stale; run pnpm gen:docs and commit it`);
  } else writeFileSync(file, body);
}
done("gen-docs");
